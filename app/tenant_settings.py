"""
Настройки одной компании — всё, что должно легко редактироваться без правки кода.

Хранятся в БД (поле Tenant.settings) в виде JSON. Pydantic-модель ниже:
  * описывает, какие поля бывают;
  * задаёт значения по умолчанию, если поле не заполнено;
  * проверяет, что в JSON нет ошибок типов.

Пример заполненных настроек: tenants/demo.json
"""

from pydantic import BaseModel, Field


class FaqItem(BaseModel):
    """Популярный вопрос и готовый ответ на него."""

    question: str
    answer: str


class LlmSettings(BaseModel):
    """Параметры модели."""

    model: str = "deepseek-chat"
    # temperature: 0 — ответы предсказуемые, 1 — более «творческие».
    # Для консультанта лучше низкая.
    temperature: float = 0.3
    max_tokens: int = 800
    # Сколько последних сообщений чата отправлять модели как контекст.
    history_limit: int = 20
    # Сколько раз подряд модель может вызвать инструменты, прежде чем ответить.
    # Защита от зацикливания.
    max_tool_rounds: int = 5


class Texts(BaseModel):
    """Готовые тексты, которые бот отправляет без участия модели."""

    unsupported_media: str = "Пока я понимаю только текстовые сообщения. Напишите, пожалуйста, текстом."
    photo_received: str = "Фото получил, передаю менеджеру — он скоро подключится."
    error_fallback: str = "Извините, у меня технические неполадки. Сейчас подключу менеджера."
    agent_unavailable: str = (
        "Сейчас все менеджеры заняты. Оставьте, пожалуйста, телефон или email — мы свяжемся с вами."
    )


class TenantSettings(BaseModel):
    """Все настройки компании. Каждый блок — отдельная часть промпта или поведения."""

    # --- Блоки промпта ---
    bot_name: str = "Ассистент"
    # Роль: кто такой бот и что он делает.
    role: str = "Ты — вежливый консультант компании. Помогаешь клиентам."
    # Стиль общения.
    style: str = "Отвечай кратко и по делу, на «вы», дружелюбно."
    # Информация о компании: чем занимается, условия, адреса и т.п.
    company_info: str = ""
    # Контакты компании, которые бот может сообщать клиентам.
    contacts: str = ""
    # Дополнительные правила: о чём нельзя говорить, как себя вести.
    rules: str = ""
    # Когда переводить на живого оператора (кроме прямой просьбы клиента).
    handoff_rules: str = "Переводи на оператора, если не знаешь ответа или клиент недоволен."
    # Языковая политика (бот будет мультиязычным).
    language: str = "Отвечай на том языке, на котором пишет клиент."
    # Популярные вопросы и ответы.
    faq: list[FaqItem] = Field(default_factory=list)

    # --- Поведение ---
    llm: LlmSettings = Field(default_factory=LlmSettings)
    texts: Texts = Field(default_factory=Texts)
    # Показывать клиенту «бот печатает...», пока готовится ответ.
    show_typing: bool = True
    # Фото: после ответа photo_received перевести на оператора.
    photo_invites_agent: bool = True
    # Возвращать диалог боту после того, как оператор закончит (has_next_transition в Jivo).
    return_to_bot_after_agent: bool = False


def load_settings(raw: dict | None) -> TenantSettings:
    """Превращает JSON из БД в объект настроек (недостающие поля — по умолчанию)."""
    return TenantSettings.model_validate(raw or {})
